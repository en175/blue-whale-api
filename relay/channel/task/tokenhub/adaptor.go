// ============================
// Request / Response structures
// ============================

type ContentItem struct {
	Type     string    `json:"type,omitempty"`
	Text     string    `json:"text,omitempty"`
	ImageURL *MediaURL `json:"image_url,omitempty"`
	VideoURL *MediaURL `json:"video_url,omitempty"`
	AudioURL *MediaURL `json:"audio_url,omitempty"`
	Role     string    `json:"role,omitempty"`
}

type MediaURL struct {
	URL string `json:"url,omitempty"`
}

type requestPayload struct {
	Model                 string         `json:"model"`
	Content               []ContentItem  `json:"content,omitempty"`
	CallbackURL           string         `json:"callback_url,omitempty"`
	ReturnLastFrame       *dto.BoolValue `json:"return_last_frame,omitempty"`
	ServiceTier           string         `json:"service_tier,omitempty"`
	ExecutionExpiresAfter *dto.IntValue  `json:"execution_expires_after,omitempty"`
	GenerateAudio         *dto.BoolValue `json:"generate_audio,omitempty"`
	Draft                 *dto.BoolValue `json:"draft,omitempty"`
	Tools                 []struct {
		Type string `json:"type,omitempty"`
	} `json:"tools,omitempty"`
	SafetyIdentifier string         `json:"safety_identifier,omitempty"`
	Priority         *dto.IntValue  `json:"priority,omitempty"`
	Resolution       string         `json:"resolution,omitempty"`
	Ratio            string         `json:"ratio,omitempty"`
	Duration         *dto.IntValue  `json:"duration,omitempty"`
	Frames           *dto.IntValue  `json:"frames,omitempty"`
	Seed             *dto.IntValue  `json:"seed,omitempty"`
	CameraFixed      *dto.BoolValue `json:"camera_fixed,omitempty"`
	Watermark        *dto.BoolValue `json:"watermark,omitempty"`
}

// responsePayload 对应 create 响应。成功时顶层 id 即上游任务ID；
// 失败（非 200）时返回 API 级错误信封，id 为空。
type responsePayload struct {
	ID             string `json:"id"`
	UpstreamTaskID string `json:"upstreamTaskId"`
	Status         string `json:"status"`
	Model          string `json:"model"`
	CreatedAt      string `json:"createdAt"`
	RequestID      string `json:"requestId"`
	Error          string `json:"error"`
	ErrorCode      int    `json:"errorCode"`
	Message        string `json:"message"`
}

// responseTask 对应查询响应。结果包在 resultSummary 信封里（与 doubao 顶层字段不同）。
type responseTask struct {
	ID             string `json:"id"`
	UpstreamTaskID string `json:"upstreamTaskId"`
	Status         string `json:"status"`
	Model          string `json:"model"`
	ResultSummary  struct {
		Content struct {
			VideoURL string `json:"video_url"`
		} `json:"content"`
		Duration       string `json:"duration"`
		Resolution     string `json:"resolution"`
		UpstreamStatus string `json:"upstreamStatus"`
		Usage          struct {
			CompletionTokens int `json:"completion_tokens"`
			TotalTokens      int `json:"total_tokens"`
		} `json:"usage"`
	} `json:"resultSummary"`
	CreatedAt string `json:"createdAt"`
	UpdatedAt string `json:"updatedAt"`
	RequestID string `json:"requestId"`
	Error     string `json:"error"`
	ErrorCode int    `json:"errorCode"`
	Message   string `json:"message"`
}

// effectiveStatus 返回用于状态判定的字段：优先 resultSummary.upstreamStatus，回退顶层 status。
func (r responseTask) effectiveStatus() string {
	if r.ResultSummary.UpstreamStatus != "" {
		return r.ResultSummary.UpstreamStatus
	}
	return r.Status
}

